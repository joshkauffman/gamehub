// Writes src/hub/gameDates.js: when each game's folder was first added and
// last changed in git, for the home page's "New" / "Updated" badges.
// Runs before `dev` and `build`. On a shallow clone (like Vercel's) git
// history is incomplete, so it leaves the checked-in file alone.
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const sh = (cmd) => { try { return execSync(cmd, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim() } catch { return '' } }

if (sh('git rev-parse --is-shallow-repository') !== 'false') {
  console.log('game-dates: no full git history here, keeping src/hub/gameDates.js as is')
  process.exit(0)
}

const app = readFileSync('src/App.jsx', 'utf8')
const dirOf = {}
for (const m of app.matchAll(/import (\w+) from '\.\/games\/([^/]+)\//g)) dirOf[m[1]] = m[2]
const dates = {}
const today = new Date().toISOString().slice(0, 10)
for (const m of app.matchAll(/<Route path="\/([^"/]+)" element={<(\w+) \/>}/g)) {
  const [, segment, comp] = m
  const dir = dirOf[comp]
  if (!dir || dates[segment]) continue
  const log = sh(`git log --format=%as -- src/games/${dir}`).split('\n').filter(Boolean)
  if (!log.length) continue
  // Uncommitted changes count as updated today.
  const dirty = sh(`git status --porcelain -- src/games/${dir}`) !== ''
  dates[segment] = { added: log[log.length - 1], updated: dirty ? today : log[0] }
}

const body = Object.entries(dates).sort().map(([k, v]) => `  '${k}': { added: '${v.added}', updated: '${v.updated}' },`).join('\n')
writeFileSync('src/hub/gameDates.js', `// Generated by scripts/game-dates.mjs — don't edit by hand.\n// Keyed by each game's route (its first path segment).\nexport const GAME_DATES = {\n${body}\n}\n`)
console.log(`game-dates: ${Object.keys(dates).length} games`)
